"""Project Onboarding: automated developer and agent orientation reports.

Generates a comprehensive, team-facing architectural overview markdown report
and structured JSON dataset from Project DNA, git history, codebase entry points,
conventions (CLIV.md and memory), and detected build/test environments.
"""

from __future__ import annotations

import datetime
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

from cliv.git import current_branch, is_git_repo, recent_commits, status_short
from cliv.intelligence.report import build_project_intelligence
from cliv.memory import MemoryStore
from cliv.security import project_root
from cliv.workspace import WorkspaceRegistry


@dataclass
class OnboardingReport:
    """Represents a generated project onboarding report."""

    project_name: str
    root_path: str
    generated_at: str
    environment: Dict[str, Any]
    dna: Dict[str, Any]
    conventions: List[Dict[str, str]]
    cliv_md: Optional[str]
    git_info: Dict[str, Any]
    workspaces: List[Dict[str, Any]]
    hotspots: List[Dict[str, Any]]

    def to_dict(self) -> Dict[str, Any]:
        """Return machine-readable dictionary representation."""
        return {
            "project_name": self.project_name,
            "root_path": self.root_path,
            "generated_at": self.generated_at,
            "environment": self.environment,
            "dna": self.dna,
            "conventions": self.conventions,
            "cliv_md": self.cliv_md,
            "git_info": self.git_info,
            "workspaces": self.workspaces,
            "hotspots": self.hotspots,
        }

    def render_markdown(self) -> str:
        """Render a clean, rich GitHub-flavored markdown onboarding guide."""
        lines: List[str] = []

        lines.append(f"# 🚀 Project Onboarding: {self.project_name}")
        lines.append("")
        lines.append(f"> Auto-generated by **cliv** on `{self.generated_at}`")
        lines.append(f"> Project Root: `{self.root_path}`")
        lines.append("")
        lines.append("---")
        lines.append("")

        # 1. Quick Start & Environment
        lines.append("## 1. ⚡ Quick Start & Environment")
        lines.append("")
        langs = self.dna.get("languages", {})
        if langs:
            sorted_langs = sorted(langs.items(), key=lambda x: x[1], reverse=True)
            lang_str = ", ".join(f"**{k}** ({v:,} bytes)" for k, v in sorted_langs[:5])
            lines.append(f"- **Languages:** {lang_str}")
        else:
            lines.append("- **Languages:** (no source code files detected)")

        pkg_systems = self.environment.get("package_managers", [])
        if pkg_systems:
            lines.append(f"- **Build / Package Managers:** {', '.join(pkg_systems)}")

        venv = self.environment.get("virtualenv")
        if venv:
            lines.append(f"- **Virtual Environment:** `{venv}`")

        test_cmd = self.environment.get("test_command", "pytest")
        lines.append(f"- **Primary Test Command:** `{test_cmd}`")

        entry_points = self.dna.get("entry_points", [])
        if entry_points:
            lines.append(f"- **Entry Points:** {', '.join(f'`{ep}`' for ep in entry_points)}")

        lines.append("")
        lines.append("### Essential Developer Commands")
        lines.append("```bash")
        if self.environment.get("setup_command"):
            lines.append(f"# Install dependencies\n{self.environment['setup_command']}")
        lines.append(f"# Run tests\n{test_cmd}")
        lines.append("# Check architectural health & components\ncliv dna")
        lines.append("# Search codebase semantically\ncliv rag query \"<topic>\"")
        lines.append("```")
        lines.append("")
        lines.append("---")
        lines.append("")

        # 2. Architecture & Topography
        lines.append("## 2. 🏗️ Architecture & Topography")
        lines.append("")
        total_files = self.dna.get("source_files", 0)
        total_symbols = self.dna.get("symbol_count", 0)
        classes = self.dna.get("class_count", 0)
        functions = self.dna.get("function_count", 0)
        methods = self.dna.get("method_count", 0)
        lines.append(
            f"- **Codebase Scale:** {total_files:,} source files · "
            f"{total_symbols:,} symbols ({classes:,} classes, {functions:,} functions, {methods:,} methods)"
        )
        lines.append("")

        components = self.dna.get("components", [])
        if components:
            lines.append("### Major Architecture Components")
            lines.append("")
            lines.append("| Component | Role | Files | Symbols | Key Files |")
            lines.append("|---|---|---|---|---|")
            for c in components:
                key_files = ", ".join(f"`{Path(f).name}`" for f in c.get("files", [])[:3])
                if len(c.get("files", [])) > 3:
                    key_files += f" *(+{len(c['files']) - 3} more)*"
                lines.append(
                    f"| **{c.get('name', c.get('key'))}** | {c.get('role', 'Component')} | "
                    f"{len(c.get('files', []))} | {c.get('symbols', 0)} | {key_files} |"
                )
            lines.append("")

        external = self.dna.get("external_packages", [])
        if external:
            lines.append("### Key External Dependencies")
            lines.append(", ".join(f"`{pkg}`" for pkg in external[:25]))
            if len(external) > 25:
                lines.append(f" *(+{len(external) - 25} more packages)*")
            lines.append("")

        lines.append("---")
        lines.append("")

        # 3. Conventions & Guidelines
        lines.append("## 3. 📋 Team Conventions & Guidelines")
        lines.append("")
        if self.cliv_md:
            lines.append("### Project Directives (`CLIV.md`)")
            lines.append("```markdown")
            lines.append(self.cliv_md.strip())
            lines.append("```")
            lines.append("")

        if self.conventions:
            lines.append("### Remembered Preferences & Guidelines")
            for conv in self.conventions:
                cat = f"[{conv.get('category', 'general')}] " if conv.get("category") else ""
                scope = f" *({conv.get('scope', 'project')})*"
                lines.append(f"- {cat}**{conv.get('content')}**{scope}")
            lines.append("")

        if not self.cliv_md and not self.conventions:
            lines.append(
                "> *No explicit conventions recorded yet. Create a `CLIV.md` file in the root "
                "or use `/memory add '<convention>'` to record team practices.*"
            )
            lines.append("")

        lines.append("---")
        lines.append("")

        # 4. Git Context & Recent Activity
        lines.append("## 4. 🌿 Git Context & Recent Activity")
        lines.append("")
        if self.git_info.get("is_repo"):
            branch = self.git_info.get("branch") or "detached HEAD"
            dirty = self.git_info.get("dirty_files_count", 0)
            dirty_str = f"⚠️ {dirty} uncommitted files" if dirty > 0 else "✓ Working tree clean"
            lines.append(f"- **Active Branch:** `{branch}` ({dirty_str})")

            commits = self.git_info.get("recent_commits", [])
            if commits:
                lines.append("")
                lines.append("### Recent Commits")
                for c in commits:
                    lines.append(f"- `{c}`")
            lines.append("")
        else:
            lines.append("> *Not inside a git repository.*")
            lines.append("")

        lines.append("---")
        lines.append("")

        # 5. Workspaces
        if self.workspaces:
            lines.append("## 5. 🗂️ Registered Multi-Repo Workspaces")
            lines.append("")
            lines.append("| Workspace | Path | Status | Description |")
            lines.append("|---|---|---|---|")
            for ws in self.workspaces:
                status = "✓ active" if ws.get("is_active") else "✓ linked"
                lines.append(
                    f"| **{ws.get('name')}** | `{ws.get('path')}` | {status} | {ws.get('description') or '-'} |"
                )
            lines.append("")
            lines.append("---")
            lines.append("")

        # 6. Architecture Hotspots & Areas for Attention
        lines.append("## 6. 🔍 Codebase Health & Hotspots")
        lines.append("")
        if self.hotspots:
            for issue in self.hotspots:
                sev = issue.get("severity", "info").upper()
                icon = "🔴" if sev == "HIGH" else ("🟡" if sev == "MEDIUM" else "ℹ️")
                lines.append(f"- {icon} **[{sev}]** {issue.get('message')}")
            lines.append("")
        else:
            lines.append("✓ No architectural bottlenecks or circular dependency warnings detected.")
            lines.append("")

        lines.append("---")
        lines.append("")

        # 7. Recommended Next Steps
        lines.append("## 7. 🧭 Recommended First Steps for New Contributors")
        lines.append("")
        lines.append("1. **Run the test suite:** Execute `{test_cmd}` to ensure all current unit tests pass.".format(test_cmd=test_cmd))
        if entry_points:
            lines.append(f"2. **Explore primary entry point:** Inspect `{entry_points[0]}` to follow control flow.")
        lines.append("3. **Inspect project components:** Run `cliv dna` for component details, or `cliv graph` to visualize import relationships.")
        lines.append("4. **Review conventions:** Follow guidelines outlined in Section 3 for styling, testing, and commits.")
        lines.append("")

        return "\n".join(lines)

    def save(self, dest: Optional[Union[str, Path]] = None) -> Path:
        """Save the markdown report to a file (defaults to <root>/ONBOARDING.md)."""
        if dest is None:
            out_path = Path(self.root_path) / "ONBOARDING.md"
        else:
            out_path = Path(dest)
            if not out_path.is_absolute():
                out_path = Path(self.root_path) / out_path

        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(self.render_markdown(), encoding="utf-8")
        return out_path


def detect_environment(root: Path) -> Dict[str, Any]:
    """Detect package managers, virtualenvs, and test runners."""
    env: Dict[str, Any] = {
        "package_managers": [],
        "virtualenv": None,
        "test_command": "pytest",
        "setup_command": None,
    }

    # Python detection
    pyproject = root / "pyproject.toml"
    setup_py = root / "setup.py"
    reqs = root / "requirements.txt"

    if pyproject.exists():
        env["package_managers"].append("pip / pyproject.toml")
        env["setup_command"] = "pip install -e ."
    elif setup_py.exists():
        env["package_managers"].append("setuptools")
        env["setup_command"] = "pip install -e ."
    elif reqs.exists():
        env["package_managers"].append("pip requirements.txt")
        env["setup_command"] = "pip install -r requirements.txt"

    # Virtual environment check
    for venv_name in [".venv", "venv", "env"]:
        if (root / venv_name).exists() and (root / venv_name).is_dir():
            env["virtualenv"] = venv_name
            break

    # JavaScript / Node detection
    pkg_json = root / "package.json"
    if pkg_json.exists():
        if (root / "pnpm-lock.yaml").exists():
            env["package_managers"].append("pnpm")
            env["test_command"] = "pnpm test"
            env["setup_command"] = "pnpm install"
        elif (root / "yarn.lock").exists():
            env["package_managers"].append("yarn")
            env["test_command"] = "yarn test"
            env["setup_command"] = "yarn install"
        else:
            env["package_managers"].append("npm")
            env["test_command"] = "npm test"
            env["setup_command"] = "npm install"

    # Rust detection
    if (root / "Cargo.toml").exists():
        env["package_managers"].append("cargo")
        env["test_command"] = "cargo test"
        env["setup_command"] = "cargo build"

    # Go detection
    if (root / "go.mod").exists():
        env["package_managers"].append("go modules")
        env["test_command"] = "go test ./..."
        env["setup_command"] = "go build ./..."

    # Docker detection
    if (root / "Dockerfile").exists():
        env["package_managers"].append("Docker")

    return env


def generate_onboarding_report(
    root: Optional[Union[str, Path]] = None,
) -> OnboardingReport:
    """Generate a complete OnboardingReport for the specified root directory."""
    target_root = Path(root).resolve() if root else project_root()

    # 1. Project DNA
    intel = build_project_intelligence(target_root)
    dna_dict = intel.to_dict()

    # 2. Environment
    env = detect_environment(target_root)

    # 3. Conventions and Memory
    conventions_list: List[Dict[str, str]] = []
    cliv_md_content: Optional[str] = None
    try:
        mem_store = MemoryStore(project_dir=target_root)
        entries = mem_store.list_entries()
        conventions_list = [e.to_dict() for e in entries]
        cliv_md_content = mem_store.get_cliv_md_content()
    except Exception:
        pass

    # 4. Git Information
    git_data: Dict[str, Any] = {"is_repo": False}
    try:
        if is_git_repo(cwd=str(target_root)):
            branch = current_branch(cwd=str(target_root))
            status = status_short(cwd=str(target_root))
            dirty_count = len([line for line in status.splitlines() if line.strip()])
            commits = recent_commits(limit=5, cwd=str(target_root))
            git_data = {
                "is_repo": True,
                "branch": branch,
                "dirty_files_count": dirty_count,
                "recent_commits": commits,
            }
    except Exception:
        pass

    # 5. Workspaces
    ws_list: List[Dict[str, Any]] = []
    try:
        reg = WorkspaceRegistry()
        active = reg.active_entry()
        for e in reg.list():
            ws_list.append({
                "name": e.name,
                "path": str(e.path),
                "description": e.description,
                "is_active": active and active.name == e.name,
            })
    except Exception:
        pass

    # 6. Hotspots / Issues
    hotspots = dna_dict.get("issues", [])

    return OnboardingReport(
        project_name=target_root.name,
        root_path=str(target_root),
        generated_at=datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ"),
        environment=env,
        dna=dna_dict,
        conventions=conventions_list,
        cliv_md=cliv_md_content,
        git_info=git_data,
        workspaces=ws_list,
        hotspots=hotspots,
    )
